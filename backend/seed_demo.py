def seed():
    print("① 装载示例内部制度文档 → 内部私有库")
    for name, text in SAMPLE_DOCS.items():
        chunks = doc_parser.chunk_text(text, doc_name=name)
        internal_store.remove_by_source(name)
        internal_store.add(chunks, source_ref=name)
        print(f"   《{name}》 {len(chunks)} 个分块")

    print("② 装载示例外部公开资料 → 外部公开库")
    for name, text in SAMPLE_EXTERNAL.items():
        chunks = doc_parser.chunk_text(text, doc_name=name)
        external_store.remove_by_source(name)
        external_store.add(chunks, source_ref=name)
        print(f"   《{name}》 {len(chunks)} 个分块")

    print("③ 装载已生效 Wiki 条目")
    for w in SAMPLE_WIKI:
        # 幂等：删除同名旧条目再重建
        for old in wiki_engine.list_entries():
            if old["knowledge_title"] == w["knowledge_title"]:
                wiki_engine.delete_entry(old["id"])
        candidate = wiki_engine.extract_candidate(
            w["knowledge_title"],
            f"根据《{w['source_reference']}》：{w['knowledge_content']}",
            [{"type": w["source_type"], "kind": "document",
              "ref": w["source_reference"], "score": 1.0, "snippet": ""}],
        )
        wiki_engine.approve(candidate["id"])
    print(f"   {len(SAMPLE_WIKI)} 条已生效")

    print("-" * 50)
    print("种子数据装载完成！启动服务：python main.py")
    print(f"内部库: {internal_store.stats()}  外部库: {external_store.stats()}")


if __name__ == "__main__":
    seed()
